CREATE TABLE daily_quests (
    daily_quest_id UUID NOT NULL DEFAULT gen_random_uuid(),
    quest_set_id UUID NOT NULL,
    user_id UUID NOT NULL,
    template_id UUID NOT NULL,
    quest_date DATE NOT NULL,
    slot SMALLINT NOT NULL,
    title VARCHAR(160) NOT NULL,
    media_type media_kind,
    source_scope quest_scope NOT NULL,
    target_count INT NOT NULL,
    xp_reward INT NOT NULL DEFAULT 10,
    progress_count INT NOT NULL DEFAULT 0,
    status quest_status NOT NULL DEFAULT 'ACTIVE',
    claimed_at TIMESTAMPTZ,
    CONSTRAINT daily_quests_pkey PRIMARY KEY (daily_quest_id),
    CONSTRAINT daily_quests_quest_set_id_slot_key UNIQUE (quest_set_id, slot),
    CONSTRAINT daily_quests_user_id_quest_date_template_id_key UNIQUE (user_id, quest_date, template_id),
    CHECK (slot BETWEEN 1 AND 4),
    CHECK (target_count > 0 AND progress_count BETWEEN 0 AND target_count),
    CHECK (xp_reward = target_count * CASE source_scope WHEN 'SAVED' THEN 15 ELSE 10 END),
    CHECK ((status = 'CLAIMED') = (claimed_at IS NOT NULL)),
    CHECK (status <> 'ACTIVE' OR progress_count < target_count),
    CHECK (status NOT IN ('CLAIMABLE','CLAIMED') OR progress_count = target_count)
);
